-- Usuarios que fazem login no sistema (autenticacao JWT).
-- A senha e gravada sempre em BCrypt, nunca em texto puro; os usuarios sao
-- criados pela tela de cadastro (POST /api/register), por isso nao ha seed aqui.

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL
);
